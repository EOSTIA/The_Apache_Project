#!/bin/bash
# start-all.sh
#
# Starts all 4 Spring Boot services in the background using their built jars.
# Assumes:
#   - Kafka (KRaft mode) is already running on localhost:9092 (start it yourself, see README)
#   - Redis is already running on localhost:6379 (WSL: `redis-server --daemonize yes`)
#   - You've already run `mvn clean package` in each of the 4 project folders
#
# Run this from the project root: ./scripts/start-all.sh

set -e

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOG_DIR="$ROOT_DIR/logs"
# WSL_IP="$(hostname -I | awk '{print $1}')"
mkdir -p "$LOG_DIR"

# RUNTIME_CONFIG_FILE="$ROOT_DIR/dashboard/runtime-config.js"
# cat > "$RUNTIME_CONFIG_FILE" <<EOF
